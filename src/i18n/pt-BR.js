/**
 * Busca um texto por caminho ("hud.train") e troca {variáveis}.
 * Retorna o próprio caminho se não achar (facilita achar texto faltando).
 */
export function t(path, vars) {
  let node = STR;
  for (const key of path.split('.')) {
    if (node == null) break;
    node = node[key];
  }
  if (node == null) return path;
  if (typeof node !== 'string') return node;
  if (!vars) return node;
  return node.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

