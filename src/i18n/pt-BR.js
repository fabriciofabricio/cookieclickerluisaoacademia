/** Anfitrião da academia (o "slot" seuze): Seu Zé na garagem, Dona Ivone no Iron. */
export function hostStr(host) {
  if (host === 'ivone') return { name: STR.npcs.ivone, talkName: 'a Dona Ivone', ...STR.ivone };
  return { name: STR.npcs.seuze, talkName: STR.hud.talkSeuZeName, ...STR.seuze };
}

